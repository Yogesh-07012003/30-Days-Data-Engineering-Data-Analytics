name = "  kumar  "

# Remove spaces
name = name.strip()

# Convert to uppercase
print(name.upper())

# Convert to lowercase
print(name.lower())

# Capitalize
print(name.capitalize())

# Replace
department = "information technology"
print(department.replace("information", "IT"))

# Split
full_name = "Arun Kumar"
parts = full_name.split()

print(parts)

# Join
print("-".join(parts))
